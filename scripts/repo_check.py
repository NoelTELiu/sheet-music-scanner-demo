#!/usr/bin/env python3
"""Small standard-library-only check before publishing this portfolio repository."""

import compileall
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LFS_HEADER = b"version https://git-lfs.github.com/spec/v1"
WARN_SIZE = 25 * 1024 * 1024
FAIL_SIZE = 100 * 1024 * 1024


def main():
    problems = []
    warnings = []

    for path in ROOT.rglob("*"):
        if not path.is_file() or ".git" in path.parts:
            continue
        rel = path.relative_to(ROOT)
        size = path.stat().st_size

        if size >= FAIL_SIZE:
            problems.append(f"file >=100 MiB: {rel} ({size / 1024 / 1024:.1f} MiB)")
        elif size >= WARN_SIZE:
            warnings.append(f"large file: {rel} ({size / 1024 / 1024:.1f} MiB)")

        if size <= 1024:
            try:
                head = path.read_bytes()[: len(LFS_HEADER)]
            except OSError:
                continue
            if head == LFS_HEADER:
                problems.append(f"Git LFS pointer without binary: {rel}")

    print("Compiling Python sources...")
    compile_ok = compileall.compile_dir(str(ROOT), quiet=1, force=True)
    if not compile_ok:
        problems.append("one or more Python files failed to compile")

    # Remove caches generated by this check so the working tree stays clean.
    for cache_dir in sorted(ROOT.rglob("__pycache__"), reverse=True):
        for child in cache_dir.iterdir():
            child.unlink()
        cache_dir.rmdir()

    print("\nRepository check")
    print("=" * 60)
    for warning in warnings:
        print(f"WARNING: {warning}")
    for problem in problems:
        print(f"ERROR:   {problem}")

    if problems:
        raise SystemExit(f"FAILED with {len(problems)} problem(s).")

    print("PASS: no LFS pointer stubs, no >=100 MiB files, and Python sources compile.")


if __name__ == "__main__":
    main()
